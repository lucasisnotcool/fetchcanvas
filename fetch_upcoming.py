"""
fetch_upcoming.py — Canvas upcoming assignments/todo tracker.
Added by Claude (Second Brain integration), 2026-08-12.

Runs after each fetchcanvas sync (hooked into main.py) or standalone:
    ./.venv/bin/python fetch_upcoming.py

Reads the same .env as main.py (API_TOKEN, CANVAS_BASE_URL, COURSES).
Writes:
  - <OUTPUT_PATH>/UPCOMING.md                       (OneDrive, human-readable)
  - ~/Documents/SecondBrain/15-upcoming.md          (Second Brain vault)
  - ~/Documents/SecondBrain/upcoming.json           (machine-readable)
"""

import os
import json
import hashlib
import time
from datetime import datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

import requests
from dotenv import load_dotenv

load_dotenv(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env"))

API_TOKEN = os.getenv("API_TOKEN")
CANVAS_BASE_URL = os.getenv("CANVAS_BASE_URL", "https://canvas.nus.edu.sg")
OUTPUT_PATH = (os.getenv("OUTPUT_PATH") or "").strip()
SGT = ZoneInfo("Asia/Singapore")
VAULT = os.path.expanduser("~/Documents/SecondBrain")

_raw = (os.getenv("COURSES") or "").strip()
COURSE_FILTER = None if not _raw or _raw.lower() == "all" else {c.strip() for c in _raw.split(",") if c.strip()}

HEADERS = {"Authorization": f"Bearer {API_TOKEN}"}
TIMEOUT = 30
WRITE_RETRY_DELAYS = (0, 2, 5)
LOCAL_STATE_DIR = Path.home() / ".fetchcanvas"
PUBLISH_STATE_PATH = LOCAL_STATE_DIR / "upcoming-publish-state.json"


def _get(url, params=None):
    r = requests.get(url, headers=HEADERS, params=params or {}, timeout=TIMEOUT)
    r.raise_for_status()
    return r.json()


def _parse_dt(s):
    if not s:
        return None
    try:
        return datetime.fromisoformat(s.replace("Z", "+00:00")).astimezone(SGT)
    except ValueError:
        return None


def collect():
    courses = _get(f"{CANVAS_BASE_URL}/api/v1/courses",
                   {"enrollment_state": "active", "per_page": 100})
    now = datetime.now(SGT)
    items = []
    errors = []
    for c in courses:
        code = c.get("course_code")
        if not code or (COURSE_FILTER and code not in COURSE_FILTER):
            continue
        try:
            assignments = _get(
                f"{CANVAS_BASE_URL}/api/v1/courses/{c['id']}/assignments",
                {"per_page": 100, "include[]": "submission", "order_by": "due_at"})
        except requests.RequestException as e:
            message = f"{code}: assignment fetch failed: {e}"
            print(f"[fetch_upcoming] {message}")
            errors.append(message)
            continue
        for a in assignments:
            due = _parse_dt(a.get("due_at"))
            sub = a.get("submission") or {}
            submitted = sub.get("workflow_state") not in (None, "unsubmitted")
            graded = sub.get("workflow_state") == "graded"
            # keep: anything not yet due, or due within the last 7 days (recently missed/submitted)
            if due is None or due >= now - timedelta(days=7):
                items.append({
                    "course": code,
                    "name": a.get("name"),
                    "due_at_sgt": due.strftime("%a %d %b %Y %H:%M") if due else None,
                    "due_iso": due.isoformat() if due else None,
                    "points": a.get("points_possible"),
                    "submitted": submitted,
                    "graded": graded,
                    "url": a.get("html_url"),
                })
    items.sort(key=lambda x: x["due_iso"] or "9999")
    return now, items, errors


def render_md(now, items):
    lines = [
        "# 15 — Upcoming (Canvas)",
        "",
        f"Last synced: {now.strftime('%a %d %b %Y %H:%M')} SGT — auto-generated by fetch_upcoming.py; do not edit by hand.",
        "",
    ]
    horizon = now + timedelta(days=14)
    soon = [i for i in items if i["due_iso"] and now <= datetime.fromisoformat(i["due_iso"]) <= horizon and not i["submitted"]]
    lines.append("## Due in the next 14 days")
    lines.append("")
    if soon:
        for i in soon:
            lines.append(f"- **{i['due_at_sgt']}** — [{i['course']}] {i['name']}"
                         + (f" ({i['points']:g} pts)" if i["points"] else ""))
    else:
        lines.append("- Nothing due (or nothing published yet).")
    lines.append("")
    lines.append("## All tracked items")
    lines.append("")
    lines.append("| Due (SGT) | Course | Assignment | Pts | Status |")
    lines.append("|---|---|---|---|---|")
    for i in items:
        status = "✅ graded" if i["graded"] else ("📤 submitted" if i["submitted"] else "⬜ open")
        lines.append(f"| {i['due_at_sgt'] or '—'} | {i['course']} | {i['name']} | {i['points'] or '—'} | {status} |")
    lines.append("")
    return "\n".join(lines)


def _atomic_write_text(path, contents):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_path = path.with_name(f".{path.name}.fetchcanvas.tmp")
    with open(temp_path, "w", encoding="utf-8") as f:
        f.write(contents)
    os.replace(temp_path, path)


def write_with_retry(path, contents):
    """Safely write a generated mirror without truncating an existing cloud file."""
    last_error = None
    for attempt, delay in enumerate(WRITE_RETRY_DELAYS, start=1):
        if delay:
            print(
                f"[fetch_upcoming] retrying {path} in {delay}s "
                f"(attempt {attempt}/{len(WRITE_RETRY_DELAYS)})."
            )
            time.sleep(delay)
        try:
            _atomic_write_text(path, contents)
            print(f"[fetch_upcoming] wrote {path}")
            return True, None
        except OSError as e:
            last_error = str(e)
            print(
                f"[fetch_upcoming] write attempt {attempt}/{len(WRITE_RETRY_DELAYS)} "
                f"failed for {path}: {e}"
            )
    return False, last_error or "Unknown filesystem error"


def _publish_digest(now, items):
    """Change at most once per day unless the logical assignment data changes."""
    payload = json.dumps(
        {"date": now.date().isoformat(), "items": items},
        sort_keys=True,
        ensure_ascii=False,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _load_published_digest():
    try:
        return json.loads(PUBLISH_STATE_PATH.read_text(encoding="utf-8")).get("digest")
    except (FileNotFoundError, ValueError, OSError):
        return None


def _save_published_digest(digest):
    _atomic_write_text(
        PUBLISH_STATE_PATH,
        json.dumps({"digest": digest}, indent=2) + "\n",
    )


def main():
    now, items, errors = collect()
    if errors:
        print("[fetch_upcoming] collection incomplete; preserving previous snapshots.")
        return {
            "ok": False,
            "error": "; ".join(errors),
            "items": len(items),
            "targets": [],
        }

    digest = _publish_digest(now, items)
    if digest == _load_published_digest():
        print("[fetch_upcoming] no logical changes; previous snapshots retained.")
        return {"ok": True, "error": None, "items": len(items), "targets": []}

    md = render_md(now, items)

    targets = []
    if OUTPUT_PATH:
        targets.append(os.path.join(OUTPUT_PATH, "UPCOMING.md"))
    if os.path.isdir(VAULT):
        targets.append(os.path.join(VAULT, "15-upcoming.md"))

    if not targets:
        return {
            "ok": False,
            "error": "No writable upcoming-output target is configured.",
            "items": len(items),
            "targets": [],
        }

    results = []
    for t in targets:
        ok, error = write_with_retry(t, md)
        results.append({"path": t, "ok": ok, "error": error})
        if not ok:
            errors.append(f"could not write {t}: {error}")

    if os.path.isdir(VAULT):
        json_path = os.path.join(VAULT, "upcoming.json")
        json_text = json.dumps({"synced_at": now.isoformat(), "items": items}, indent=1) + "\n"
        ok, error = write_with_retry(json_path, json_text)
        results.append({"path": json_path, "ok": ok, "error": error})
        if not ok:
            errors.append(f"could not write {json_path}: {error}")

    if not errors:
        try:
            _save_published_digest(digest)
        except OSError as e:
            errors.append(f"could not record local publish state: {e}")

    print(f"[fetch_upcoming] {len(items)} items tracked.")
    return {
        "ok": not errors,
        "error": "; ".join(errors) if errors else None,
        "items": len(items),
        "targets": results,
    }


if __name__ == "__main__":
    result = main()
    raise SystemExit(0 if result["ok"] else 10)
